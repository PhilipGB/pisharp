"""Differential case matrix for the core agent loop: active steering, follow-up,
abort, failure, and concurrency behavior.

Each case runs against both products with:
  * the same deterministic MCP server (non-idempotent side-effecting tools and
    explicit file-based gates),
  * the same scripted local Chat Completions provider (file-based pre-content
    gates and mid-stream chunk gates),
  * the same RPC command script with deterministic barriers.

Case scripts use tuples ``(method, args)`` or bare strings for harness
actions.  ``gates`` lists every gate token the script (or teardown) must be
able to release; ``settles`` is the expected number of agent settlements.
"""

